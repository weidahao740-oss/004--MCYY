function learningLine(
  id: string,
  purpose: FixedContentLine['purpose'],
  english: string,
  textZh: string,
  audioRequired = true,
): FixedContentLine {
  const contentId = `${id}_content`
  return {
    id,
    speaker: purpose === 'reference_reply' ? 'system_example' : 'morrow',
    purpose,
    learningContent: {
      contentId,
      textVersion: '1.0.0',
      english,
      translation: {
        textZh,
        version: '1.0.0',
        status: 'manual_reviewed',
        reviewedBy: 'content_owner',
      },
    },
    audioRequired,
    audioIds: audioRequired ? [`${id}_audio`] : [],
  }
}

